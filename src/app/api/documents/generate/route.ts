import { NextRequest, NextResponse } from 'next/server';
import { Document, Packer, Paragraph, TextRun, HeadingLevel } from 'docx';
import jsPDF from 'jspdf';
import { db } from '@/lib/db';

export async function POST(req: NextRequest) {
  try {
    const body = await req.json();
    const { title = 'JARVIS Generated Document', format = 'pdf', content = '', docType = 'report' } = body;

    // Save document record in database
    db.addDocument({
      id: `doc_${Date.now()}`,
      userId: 'usr_jarvis_master',
      title,
      docType,
      format,
      content,
      createdAt: new Date().toISOString(),
    });

    if (format === 'docx') {
      const doc = new Document({
        sections: [
          {
            properties: {},
            children: [
              new Paragraph({
                text: title,
                heading: HeadingLevel.HEADING_1,
              }),
              new Paragraph({
                children: [
                  new TextRun({
                    text: `Generated by JARVIS AI 2.0 Operating System\nDate: ${new Date().toLocaleDateString()}\n\n`,
                    italics: true,
                    size: 20,
                  }),
                ],
              }),
              ...content.split('\n').map(
                (line: string) =>
                  new Paragraph({
                    children: [new TextRun({ text: line, size: 24 })],
                  })
              ),
            ],
          },
        ],
      });

      const buffer = await Packer.toBuffer(doc);
      return new NextResponse(new Uint8Array(buffer), {
        status: 200,
        headers: {
          'Content-Type': 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
          'Content-Disposition': `attachment; filename="${encodeURIComponent(title.toLowerCase().replace(/\s+/g, '_'))}.docx"`,
        },
      });
    } else if (format === 'pdf') {
      const doc = new jsPDF();
      doc.setFont('Helvetica', 'bold');
      doc.setFontSize(18);
      doc.text(title, 14, 22);

      doc.setFont('Helvetica', 'normal');
      doc.setFontSize(10);
      doc.setTextColor(100);
      doc.text(`Generated by JARVIS AI 2.0 | ${new Date().toLocaleString()}`, 14, 30);

      doc.setFontSize(12);
      doc.setTextColor(20);

      const splitText = doc.splitTextToSize(content || 'Document content prepared by JARVIS executive workspace.', 180);
      doc.text(splitText, 14, 42);

      const pdfArrayBuffer = doc.output('arraybuffer');
      return new NextResponse(new Uint8Array(pdfArrayBuffer), {
        status: 200,
        headers: {
          'Content-Type': 'application/pdf',
          'Content-Disposition': `attachment; filename="${encodeURIComponent(title.toLowerCase().replace(/\s+/g, '_'))}.pdf"`,
        },
      });
    } else if (format === 'csv') {
      const csvData = `Title,Type,GeneratedAt\n"${title}","${docType}","${new Date().toISOString()}"\n\nContent\n"${content.replace(/"/g, '""')}"`;
      return new NextResponse(csvData, {
        status: 200,
        headers: {
          'Content-Type': 'text/csv',
          'Content-Disposition': `attachment; filename="${encodeURIComponent(title.toLowerCase().replace(/\s+/g, '_'))}.csv"`,
        },
      });
    }

    // Default markdown
    const mdContent = `# ${title}\n*Generated by JARVIS AI 2.0 on ${new Date().toISOString()}*\n\n${content}`;
    return new NextResponse(mdContent, {
      status: 200,
      headers: {
        'Content-Type': 'text/markdown',
        'Content-Disposition': `attachment; filename="${encodeURIComponent(title.toLowerCase().replace(/\s+/g, '_'))}.md"`,
      },
    });
  } catch (error: any) {
    console.error('Doc gen error:', error);
    return NextResponse.json({ error: error.message }, { status: 500 });
  }
}
